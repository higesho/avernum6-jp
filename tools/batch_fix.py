def main(tdir):
    d = os.path.join(tdir, 'ja')
    n = 0
    for fn in os.listdir(d):
        if fn.endswith('__known.json'):
            continue
        p = os.path.join(d, fn)
        s = open(p, encoding='utf-8').read()
        o = s
        for a, b in REPL:
            s = s.replace(a, b)
        for rx, b in RX:
            s = rx.sub(b, s)
        if s != o:
            open(p, 'w', encoding='utf-8').write(s)
            n += 1
    print(f'{n} files fixed')


if __name__ == '__main__':
    main(sys.argv[1])
