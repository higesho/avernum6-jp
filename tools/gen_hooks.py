"""Make the byte patterns and value table the DLL uses to find its hook points (src_hooks.c).

usage:
    python -I gen_hooks.py SPEC_MODULE EXE OUT_C

SPEC_MODULE (in tools/) defines
    PATTERNS = [(name, start_va, end_va), ...]        code ranges; must be unique in .text
    VALUES   = [(name, pattern, kind, steam_value), ...]
        kind 'start': the pattern's own address (a function to replace or call)
             'at':    an address inside the pattern (code to patch or jump to)
             'abs':   an absolute address / immediate inside the pattern (a relocated dword)
             'call':  the target of a call rel32 inside the pattern
In a pattern, relocated dwords and call/jmp rel32 operands are wildcards (they differ between
builds); everything else must match. The offsets of the values inside their pattern are written
to OUT_C together with the patterns, and checked against this exe.
"""
import importlib
import os
import sys

import capstone
import pefile

sys.stdout.reconfigure(encoding='utf-8')


def main(argv):
    spec = importlib.import_module(argv[0])
    pe = pefile.PE(argv[1])
    base = pe.OPTIONAL_HEADER.ImageBase
    img = pe.get_memory_mapped_image()
    text = [s for s in pe.sections if s.Name.startswith(b'.text')][0]
    t0, tn = text.VirtualAddress, text.Misc_VirtualSize
    tdata = img[t0:t0 + tn]
    relocs = set()
    for blk in pe.DIRECTORY_ENTRY_BASERELOC:
        for e in blk.entries:
            if e.type == 3:
                relocs.add(e.rva)
    md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_32)
    pats, offs = {}, {}
    for name, s, e in spec.PATTERNS:
        code = img[s - base:e - base]
        mask = [1] * len(code)
        for k in range(len(code)):
            if (s - base + k) in relocs:
                for j in range(4):
                    if k + j < len(code):
                        mask[k + j] = 0
        calls = {}
        for ins in md.disasm(code, s):
            if ins.mnemonic in ('call', 'jmp') and ins.bytes[0] in (0xE8, 0xE9) and ins.size == 5:
                k = ins.address - s
                for j in range(1, 5):
                    mask[k + j] = 0
                calls[ins.address - s + 1] = int(ins.op_str, 16)
        pat = ' '.join('%02X' % b if m else '??' for b, m in zip(code, mask))
        # unique in .text?
        hits = []
        n = len(code)
        first = [i for i in range(n) if mask[i]][0]
        start = 0
        while True:
            i = tdata.find(bytes([code[first]]), start)
            if i < 0:
                break
            p = i - first
            if 0 <= p <= len(tdata) - n and all(not mask[j] or tdata[p + j] == code[j] for j in range(n)):
                hits.append(base + t0 + p)
            start = i + 1
        if hits != [s]:
            raise SystemExit(f'pattern {name}: matches {[hex(h) for h in hits]}')
        pats[name] = (s, pat, code, mask, calls)
    vals = []
    e_of = {name: e for name, s, e in spec.PATTERNS}
    for vname, pname, kind, value in spec.VALUES:
        s, pat, code, mask, calls = pats[pname]
        if kind == 'start':
            if value != s:
                raise SystemExit(f'{vname}: start {hex(s)} != {hex(value)}')
            off = 0
        elif kind == 'at':
            off = value - s
            if not 0 <= off < e_of[pname] - s:
                raise SystemExit(f'{vname}: {hex(value)} outside {pname}')
            kind = 'start'
        elif kind == 'abs':
            off = next((k for k in range(len(code) - 3) if (s - base + k) in relocs
                        and int.from_bytes(code[k:k + 4], 'little') == value), None)
            if off is None:
                raise SystemExit(f'{vname}: {hex(value)} not found in {pname}')
        elif kind == 'call':
            off = next((k for k, t in calls.items() if t == value), None)
            if off is None:
                raise SystemExit(f'{vname}: call to {hex(value)} not found in {pname}')
        vals.append((vname, pname, kind, off, value))
    names = [p[0] for p in spec.PATTERNS]
    out = ['// Generated by tools/gen_hooks.py from the Steam build. Do not edit by hand.',
           'static const HookPat kHookPats[] = {']
    for name, s, e in spec.PATTERNS:
        out.append(f'    {{"{name}", 0x{s:06x}, "{pats[name][1]}"}},')
    out.append('};')
    out.append('enum { ' + ', '.join('HP_' + n.upper() for n in names) + ', HP_COUNT };')
    out.append('static const HookVal kHookVals[] = {')
    for vname, pname, kind, off, value in vals:
        out.append(f'    {{"{vname}", HP_{pname.upper()}, HK_{kind.upper()}, {off}, 0x{value:06x}}},')
    out.append('};')
    out.append('enum { ' + ', '.join('HV_' + v[0].upper() for v in vals) + ', HV_COUNT };')
    open(argv[2], 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
    print(f'{len(names)} patterns ({sum(e - s for _, s, e in spec.PATTERNS)} bytes), {len(vals)} values -> {argv[2]}')


if __name__ == '__main__':
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    main(sys.argv[1:])
